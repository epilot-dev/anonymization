/** Whether a compact IBAN has a known country code and that country's length. */
export const hasIbanCountryLength = (compact: string): boolean => {
  const length = IBAN_LENGTHS[compact.slice(0, 2)];

  return typeof length === 'number' ? length === compact.length : length?.includes(compact.length) === true;
};
